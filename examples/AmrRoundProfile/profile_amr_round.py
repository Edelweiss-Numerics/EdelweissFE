#!/usr/bin/env python3
"""P0 of PLAN_TOPOLOGY_PIPELINE.md: what does one topology round actually cost, and does that cost
scale with the *change* or with the *whole mesh*?

The question matters because `b0eb74f` bought its 2.04x replay speedup by collapsing 54
per-occasion materialisations into one -- i.e. by making the replay unfaithful. Faithful replay
(P2) hands that speedup back, so it has to be re-earned by making the per-round work incremental
instead. Which work, and how much, is what this measures.

Method: refine a FIXED number of elements (one, chosen by an elementSet marker) in meshes of
growing size. Any stage whose cost grows with the mesh is doing whole-mesh work for a local change
-- that is the incrementality opportunity. Any stage that stays flat is already proportional to the
change and can be left alone.

Run on xeon (see PLAN §0.2 -- idle machine, and never on the notebook):

    python3 profile_amr_round.py 4 8 12
"""

