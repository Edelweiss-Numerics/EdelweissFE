# The stages this is about: everything below is per-round work whose scaling we want to classify.
STAGES = [
    "topology update",
    "hanging: whole-mesh index build",
    "hanging: interface-shell scan",
    "elements & state transfer",
    "sets & fields sync",
    "fields resize & restore",
    "relink field variables",
    "notify observers",
    "refresh mesh dependents",
]


def runOne(n: int, workdir: Path, template=None, tag="") -> dict[str, float]:
    template = template or TEMPLATE
    case = workdir / "case_{:}{:}".format(tag, n)
    case.mkdir(parents=True, exist_ok=True)
    (case / "test.inp").write_text(template.format(n=n))

    out = subprocess.run(["edelweissfe", "test.inp"], cwd=case, capture_output=True, text=True, check=False).stdout

    timings = {}
    for stage in STAGES:
        # the performancetiming table prints "| <stage> | <value> s |", wrapped to a fixed width
        match = re.search(re.escape(stage) + r"\s*\|\s*([0-9.eE+-]+)\s*s", out)
        if match:
            timings[stage] = float(match.group(1))
    timings["_elements"] = float(len(re.findall(r"^", out)))  # placeholder, replaced below
    match = re.search(r"elements:\s*(\d+)", out)
    if match:
        timings["_elements"] = float(match.group(1))
    return timings


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    withTie = "--tie" in sys.argv
    sizes = [int(a) for a in args] or [4, 8, 12]
    workdir = Path(__file__).parent / "_runs"
    template, tag = (TIE_TEMPLATE, "tie") if withTie else (TEMPLATE, "")
    results = {n: runOne(n, workdir, template, tag) for n in sizes}

    print("\n{:38} {:}".format("stage [s]", "  ".join("nX={:<10}".format(n) for n in sizes)))
    print("-" * (38 + 14 * len(sizes)))
    print("{:38} {:}".format("elements", "  ".join("{:<12.0f}".format(results[n].get("_elements", 0)) for n in sizes)))
    for stage in STAGES:
        row = "  ".join("{:<12.4f}".format(results[n].get(stage, float("nan"))) for n in sizes)
        print("{:38} {:}".format(stage, row))

    print(
        "\nA stage growing roughly with the element count is doing whole-mesh work for a one-element\n"
        "refinement -- that is where incrementality pays (PLAN_TOPOLOGY_PIPELINE.md P6). A flat stage\n"
        "is already proportional to the change."
    )


if __name__ == "__main__":
    main()
